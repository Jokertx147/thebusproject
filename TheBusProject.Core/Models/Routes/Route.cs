namespace TheBusProject.Models.Routes
{
    [Serializable]
    //the class for a route
    public abstract class Route : BaseModel
    {
        #region Constants

        public const double MinRouteDistance = 10;

        #endregion

        #region Constructors and Destructors

        protected Route(RouteType type, string id, Station destination1, Station destination2, DateTime startDate)
        {
            Type = type;
            Id = id;
            Destination1 = destination1;
            Destination2 = destination2;
            StartDate = startDate;

            TimeTable = new RouteTimeTable(this);
            Invoices = new Invoices();
            Statistics = new RouteStatistics();
            Banned = false;
            Stopovers = new List<StopoverRoute>();

            Season = Weather.Season.AllYear;
        }

        protected Route(SerializationInfo info, StreamingContext ctxt) : base(info, ctxt)
        {
            if (Version == 1)
            {
                StartDate = new DateTime(1950, 1, 1);
            }
        }

        #endregion

        #region Enums

        /// <summary>
        ///     What a route carries. Only passengers, now: the Cargo and Mixed kinds, and the Helicopter kind left
        ///     over from the airline this was forked from, are gone. Carrying freight is a different game, and the
        ///     dimension cost something everywhere it was threaded - every switch on this enum, a route class and a
        ///     coach class of its own, a second demand model on every station, its own terminals, statistics and
        ///     screens - for a side of the game nothing in a bus simulator needed.
        /// </summary>
        public enum RouteType
        {
            Passenger
        }

        #endregion

        #region Public Properties

        [Versioning("carrier")]
        public Carrier Carrier { get; set; }

        public double Balance => GetBalance();

        [Versioning("banned")]
        public bool Banned { get; set; }

        [Versioning("destination1")]
        public Station Destination1 { get; set; }

        [Versioning("destination2")]
        public Station Destination2 { get; set; }

        public double FillingDegree => GetFillingDegree();


        public bool HasStopovers => Stopovers.Count > 0;

        [Versioning("id")]
        public string Id { get; set; }

        [Versioning("invoices")]
        public Invoices Invoices { get; set; }

        public bool IsCargoRoute => Type == RouteType.Cargo;

        /// <summary>
        ///     What a seat on this leg is really worth, against the leg's own fare. A leg of a service carries two
        ///     sorts of passenger: the ones riding only this leg, who pay its fare, and the ones riding through on a
        ///     ticket for a longer journey, whose fare is spread over every leg they sit on. A coach fare per mile
        ///     falls a long way with distance, so a through rider is worth much less on any one leg than somebody who
        ///     got on and off at its ends. 1 on a route that runs non-stop, and set by RouteStops.Reprice otherwise.
        /// </summary>
        [Versioning("throughfare")]
        public double ThroughFareFactor { get; set; } = 1;

        // connecting passengers (see ConnectionService): this month's counts and last month's
        [Versioning("connmonth")]
        public int ConnectMonth { get; set; }

        [Versioning("connpax")]
        public int ConnectPassengers { get; set; }

        [Versioning("connall")]
        public int ConnectAllPassengers { get; set; }

        [Versioning("connlastpax")]
        public int ConnectLastPassengers { get; set; }

        [Versioning("connlastall")]
        public int ConnectLastAllPassengers { get; set; }

        // seats flown in the same months, for the load factor
        [Versioning("connseats")]
        public int ConnectSeats { get; set; }

        [Versioning("connlastseats")]
        public int ConnectLastSeats { get; set; }

        [Versioning("lastupdated")]
        public DateTime LastUpdated { get; set; }

        [Versioning("season")]
        public Weather.Season Season { get; set; }

        [Versioning("startdate", Version = 2, AutoGenerated = false)]
        public DateTime StartDate { get; set; }

        [Versioning("statistics")]
        public RouteStatistics Statistics { get; set; }

        [Versioning("stopovers")]
        public List<StopoverRoute> Stopovers { get; set; }

        [Versioning("timetable")]
        public RouteTimeTable TimeTable { get; set; }

        [Versioning("type")]
        public RouteType Type { get; set; }

        #endregion

        #region Public Methods and Operators

        public override void GetObjectData(SerializationInfo info, StreamingContext context)
        {
            AddVersion(info, 2);

            base.GetObjectData(info, context);
        }

        public void AddRouteInvoice(Invoice invoice)
        {
            Invoices.AddInvoice(invoice);
        }

        //adds a stop over to the route
        public void AddStopover(StopoverRoute stopover)
        {
            Stopovers.Add(stopover);
            RouteIndex.Invalidate();
        }

        public void ClearRouteStats()
        {
            Statistics.Stats.Clear();
        }

        //removes a stop over from the route

        //returns if the route contains a specific destination
        public bool ContainsDestination(Station destination)
        {
            return Destination1 == destination || Destination2 == destination;
        }

        /// <summary>The coach flying the route: those of its timetable entries, then those of their main entries (each once, in that order).</summary>
        public List<FleetCoach> GetCoaches()
        {
            RouteTimeTableEntry[] entries = Entries();
            var result = new List<FleetCoach>();
            var seen = new HashSet<FleetCoach>();
            foreach (var e in entries)
            {
                var a = e?.Coach;
                if (a != null && seen.Add(a)) result.Add(a);
            }
            foreach (var e in entries)
            {
                var a = e?.MainEntry?.Coach;
                if (a != null && seen.Add(a)) result.Add(a);
            }
            return result;
        }

        // a copy of the timetable's entries (the game thread may be changing the list)
        private RouteTimeTableEntry[] Entries()
        {
            var list = TimeTable?.Entries;
            if (list == null) return new RouteTimeTableEntry[0];
            for (int attempt = 0; ; attempt++)
            {
                try
                {
                    return list.ToArray();
                }
                catch (ArgumentException) when (attempt < 3)
                {
                    // the list changed while copying: try again
                }
            }
        }

        /// <summary>Whether any coach flies the route (as GetCoaches().Count > 0, without building the list).</summary>
        public bool HasCoach
        {
            get
            {
                var list = TimeTable?.Entries;
                if (list == null) return false;
                try
                {
                    for (int i = 0; i < list.Count; i++)
                    {
                        var e = list[i];
                        if (e?.Coach != null || e?.MainEntry?.Coach != null) return true;
                    }
                    return false;
                }
                catch (ArgumentOutOfRangeException)
                {
                    // the list got shorter while reading
                    return GetCoaches().Count > 0;
                }
            }
        }

        public double GetBalance(DateTime startTime, DateTime endTime)
        {
            return GetRouteInvoiceAmount(Invoice.InvoiceType.Total, startTime, endTime);
        }

        public FleetCoach GetCurrentCoach()
        {
            return
                GetCoaches().Find(f => f.CurrentTrip != null && f.CurrentTrip.Entry.TimeTable.Route == this);
        }

        //returns the list of destinations
        public List<Station> GetDestinations()
        {
            var dests = new List<Station> {Destination1, Destination2};

            return dests;
        }

        public double GetDistance()
        {
            if (HasStopovers)
            {
                return Stopovers.SelectMany(s => s.Legs).Max(l => l.GetDistance());
            }
            return
                Destination1.Profile.Coordinates.ConvertToGeoCoordinate()
                            .GetDistanceTo(Destination2.Profile.Coordinates.ConvertToGeoCoordinate())/1000;
        }

        public abstract double GetFillingDegree();

        public TimeSpan GetTripTime(CoachType type)
        {
            if (HasStopovers)
            {
                double totalMinutes = Stopovers.SelectMany(s => s.Legs)
                                               .Sum(l => l.GetTripTime(type).TotalMinutes);
                double totalRestTime = FleetCoachHelpers.GetMinTimeBetweenTrips(type).TotalMinutes
                                       *(Stopovers.SelectMany(s => s.Legs).Count() - 1);
                var time = (int) (totalRestTime + totalMinutes);

                return new TimeSpan(0, time, 0);
            }
            return MathHelpers.GetTripTime(Destination1, Destination2, type);
        }

        //returns all invoices for the route
        public Invoices GetInvoices()
        {
            return Invoices;
        }

        //returns invoices amount for a specific type for a route
        public double GetRouteInvoiceAmount(Invoice.InvoiceType type)
        {
            double amount = Stopovers.Sum(stopover => stopover.Legs.Sum(l => l.GetRouteInvoiceAmount(type)));

            if (type == Invoice.InvoiceType.Total)
            {
                amount += Invoices.GetAmount();
            }
            else
            {
                amount += Invoices.GetAmount(type);
            }

            return amount;
        }

        //returns the invoices amount for a specific type for a period
        public double GetRouteInvoiceAmount(Invoice.InvoiceType type, DateTime startTime, DateTime endTime)
        {
            int startYear = startTime.Year;
            int endYear = endTime.Year;

            int startMonth = startTime.Month;
            int endMonth = endTime.Month;

            int totalMonths = (endMonth - startMonth) + 12*(endYear - startYear);

            double totalAmount = 0;

            var date = new DateTime(startYear, startMonth, 1);

            for (int i = 0; i < totalMonths; i++)
            {
                if (type == Invoice.InvoiceType.Total)
                {
                    totalAmount += Invoices.GetAmount(date.Year, date.Month);
                }
                else
                {
                    totalAmount += Invoices.GetAmount(type, date.Year, date.Month);
                }

                date = date.AddMonths(1);
            }

            return totalAmount;
        }

        //returns the list of invoice types for a route
        public List<Invoice.InvoiceType> GetRouteInvoiceTypes()
        {
            var types = new List<Invoice.InvoiceType>
                {
                    Invoice.InvoiceType.Tickets,
                    Invoice.InvoiceType.OnTripIncome,
                    Invoice.InvoiceType.Fees,
                    Invoice.InvoiceType.Maintenances,
                    Invoice.InvoiceType.TripExpenses,
                    Invoice.InvoiceType.Wages,
                    Invoice.InvoiceType.Total
                };

            return types;
        }

        public void RemoveStopover(Station stopover)
        {
            Stopovers.Remove(Stopovers.Find(s => s.Stopover == stopover));
        }

        public void SetRouteInvoice(Invoice.InvoiceType type, int year, int month, int day, double amount)
        {
            Invoices.AddInvoice(type, year, month, day, amount);
        }

        #endregion

        #region Methods

        private double GetBalance()
        {
            return GetRouteInvoiceAmount(Invoice.InvoiceType.Total);
        }

        #endregion

        //returns the balance for the route for a period

